#!/usr/bin/env python3
"""
Injects custom .p7m intent filters into the generated Tauri AndroidManifest.xml.
Preserves all original attributes, themes (@style/Theme.Tauri), and activities generated by Tauri.
"""

import sys
import os

INTENT_FILTERS = """
            <!-- Intent Filter 1: Official and common PKCS#7 / CAdES MIME types -->
            <intent-filter android:label="Apri con ZeroP7M">
                <action android:name="android.intent.action.VIEW" />
                <category android:name="android.intent.category.DEFAULT" />
                <category android:name="android.intent.category.BROWSABLE" />
                <data android:scheme="content" />
                <data android:scheme="file" />
                <data android:mimeType="application/pkcs7-mime" />
                <data android:mimeType="application/x-pkcs7-mime" />
                <data android:mimeType="application/pkcs7-signature" />
                <data android:mimeType="application/x-pkcs7-signature" />
            </intent-filter>

            <!-- Intent Filter 2: Generic / octet-stream files with .p7m / .P7M extension -->
            <intent-filter android:label="Apri con ZeroP7M">
                <action android:name="android.intent.action.VIEW" />
                <category android:name="android.intent.category.DEFAULT" />
                <category android:name="android.intent.category.BROWSABLE" />
                <data android:scheme="content" />
                <data android:scheme="file" />
                <data android:mimeType="*/*" />
                <data android:pathPattern=".*\\\\.p7m" />
                <data android:pathPattern=".*\\\\..*\\\\.p7m" />
                <data android:pathPattern=".*\\\\..*\\\\..*\\\\.p7m" />
                <data android:pathPattern=".*\\\\.P7M" />
                <data android:pathPattern=".*\\\\..*\\\\.P7M" />
                <data android:pathPattern=".*\\\\..*\\\\..*\\\\.P7M" />
                <data android:pathSuffix=".p7m" />
                <data android:pathSuffix=".P7M" />
            </intent-filter>

            <!-- Intent Filter 3: URI schemes without MIME type from system file managers -->
            <intent-filter android:label="Apri con ZeroP7M">
                <action android:name="android.intent.action.VIEW" />
                <category android:name="android.intent.category.DEFAULT" />
                <category android:name="android.intent.category.BROWSABLE" />
                <data android:scheme="content" />
                <data android:scheme="file" />
                <data android:pathPattern=".*\\\\.p7m" />
                <data android:pathPattern=".*\\\\..*\\\\.p7m" />
                <data android:pathPattern=".*\\\\..*\\\\..*\\\\.p7m" />
                <data android:pathPattern=".*\\\\.P7M" />
                <data android:pathPattern=".*\\\\..*\\\\.P7M" />
                <data android:pathPattern=".*\\\\..*\\\\..*\\\\.P7M" />
                <data android:pathSuffix=".p7m" />
                <data android:pathSuffix=".P7M" />
            </intent-filter>

            <!-- Intent Filter 4: ACTION_SEND & ACTION_SEND_MULTIPLE for sharing from other apps -->
            <intent-filter android:label="Apri con ZeroP7M">
                <action android:name="android.intent.action.SEND" />
                <action android:name="android.intent.action.SEND_MULTIPLE" />
                <category android:name="android.intent.category.DEFAULT" />
                <data android:mimeType="application/pkcs7-mime" />
                <data android:mimeType="application/x-pkcs7-mime" />
                <data android:mimeType="application/pkcs7-signature" />
                <data android:mimeType="application/x-pkcs7-signature" />
                <data android:mimeType="application/octet-stream" />
                <data android:mimeType="*/*" />
            </intent-filter>
"""

def main():
    manifest_path = sys.argv[1] if len(sys.argv) > 1 else "apps/tauri/src-tauri/gen/android/app/src/main/AndroidManifest.xml"
    if not os.path.exists(manifest_path):
        print(f"[WARN] Manifest not found at {manifest_path}, skipping injection.")
        return

    with open(manifest_path, "r", encoding="utf-8") as f:
        content = f.read()

    if "Apri con ZeroP7M" in content:
        print("[INFO] Intent filters already present in AndroidManifest.xml.")
        return

    # Find the closing </activity> tag of MainActivity
    idx = content.rfind("</activity>")
    if idx == -1:
        print("[ERROR] Could not find </activity> tag in AndroidManifest.xml.")
        sys.exit(1)

    new_content = content[:idx] + INTENT_FILTERS + "\n        " + content[idx:]

    with open(manifest_path, "w", encoding="utf-8") as f:
        f.write(new_content)

    print(f"[OK] Successfully injected .p7m intent filters into {manifest_path}")

if __name__ == "__main__":
    main()
