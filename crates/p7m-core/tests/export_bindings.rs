use std::fs;
use std::path::PathBuf;
use ts_rs::{Config, TS};

use p7m_core::{
    DocumentKind, EncodingFormat, IntegrityStatus, P7MError, P7MErrorCode, P7MInspectionReport,
    RevocationStatus, SignatureLayer, SignerSummary,
};

#[test]
fn export_bindings() {
    let cfg = Config::default();

    let mut out = String::new();
    out.push_str("// Auto-generated by p7m-core (ts-rs). DO NOT EDIT MANUALLY.\n");
    out.push_str("// Run `cargo test -p p7m-core export_bindings` to regenerate.\n\n");

    let declarations = [
        format!("export {}", DocumentKind::decl(&cfg)),
        format!("export {}", EncodingFormat::decl(&cfg)),
        format!("export {}", IntegrityStatus::decl(&cfg)),
        format!("export {}", RevocationStatus::decl(&cfg)),
        format!("export {}", SignerSummary::decl(&cfg)),
        format!("export {}", SignatureLayer::decl(&cfg)),
        format!("export {}", P7MInspectionReport::decl(&cfg)),
        format!("export {}", P7MErrorCode::decl(&cfg)),
        format!("export {}", P7MError::decl(&cfg)),
    ];

    for decl in declarations {
        out.push_str(&decl);
        out.push_str("\n\n");
    }

    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let target_path = manifest_dir.join("../../packages/shared-types/src/generated.ts");

    if let Some(parent) = target_path.parent() {
        fs::create_dir_all(parent).expect("Failed to create target directory");
    }

    if std::env::var("CHECK_BINDINGS_DRIFT").as_deref() == Ok("1") {
        let existing = fs::read_to_string(&target_path).unwrap_or_default();
        assert_eq!(
            existing, out,
            "TypeScript bindings are out of date. Run `cargo test -p p7m-core export_bindings`."
        );
    } else {
        fs::write(&target_path, &out).expect("Failed to write generated TypeScript bindings");
    }
}
